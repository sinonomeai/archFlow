export const DESIGN_REVIEW_PROMPT = `你刚刚已经根据约束生成了一版架构图。现在做一次设计复核。

判断标准：
- 是否有一个取舍会实质改变架构结构、部署单元或主要依赖？
- 这个取舍是否还没有被已收集约束回答？
- 如果不问，用户是否可能拿到一个方向错误的方案？

检查清单（逐项确认，未确认且会改变架构的必须问）：
- 规模与并发：用户量、并发播放规模；
- 月度云预算：可接受的支出上限；
- 版权与合规：付费、版权记录、内容审核要求；
- 第三方音源接入：服务端代理音频流、客户端直连，还是只做元数据转换；
- 技术栈与接口风格：前端/后端语言框架、REST/GraphQL/tRPC；
- 认证与授权：JWT/Session/OAuth、角色与权限模型；
- 数据库与路由：主数据库、核心表、前后端路由组织；
- 其他会改变部署单元或主要依赖的取舍：缓存、队列、可观测性、部署运维。

规则：
1. 每轮只问一个问题，不要一次抛出多个问题。
2. 已经出现在“已收集约束”里的字段，不要再问；用户选择“暂不确定”也视为已确认。
3. 只有检查清单里的高影响项都已被确认，或者剩下的只是实现细节，才调用 finish_design。
4. 不要在最终文字里列出本可以直接让用户选择的约束；该问的必须用卡片问。
5. 如果确实需要用户拍板，调用 ask_design_card：
   - field 只能取 database / cache / queue / auth / observability / scale / budget / compliance / integration / availability / other；
   - title 简短，question 具体；
   - intro 用一两句说明“为什么现在要问”，会先展示给用户；
   - kind 用 single 或 multi；
   - options 给 2-6 个互斥选项，提供 value / label / 可选 description，并包含“暂不确定”或“暂不需要”作为可选项。
6. 不要问“要不要继续”“是否满意”这类空泛问题，也不要重复架构图里已经写明的信息。`;
